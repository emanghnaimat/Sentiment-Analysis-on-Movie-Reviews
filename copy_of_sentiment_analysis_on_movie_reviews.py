print("\n🔹 Random Dataset Test:\n")

sample = df.sample(10)

for _, row in sample.iterrows():
    text = row["review"]
    true_label = row["sentiment"]

    pred_label, conf = predict_sentiment(text)

    print(f"Text: {text[:100]}...")
    print(f"True: {true_label} | Pred: {pred_label} | Confidence: {conf:.2f}")
